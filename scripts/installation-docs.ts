import { readFileSync } from "node:fs";
import { join } from "node:path";

import type { Registry } from "../cli/types.ts";
import type {
  InstallationSnippetKey,
  InstallationSnippets,
} from "../src/lib/installation-snippets.ts";
import { cliCommand, copyComponentsCommand } from "../src/lib/site.ts";
import { highlightCode, type HighlightLanguage } from "./highlight.ts";

const sharedPackages = ["class-variance-authority", "@floating-ui/react-dom", "lucide-preact"];

function exact(versions: Record<string, string>, names?: string[]) {
  return Object.entries(versions)
    .filter(([name]) => !names || names.includes(name))
    .map(([name, version]) => `${name}@${version}`)
    .join(" ");
}

/**
 * Every code block of /docs/installation, highlighted at build time. The snippets mirror
 * `scripts/install-flow.ts`, which replays them on a fresh Vite project; change both together.
 * Versions come from the CLI registry and the root manifest, never retyped.
 */
export function installationSnippets(
  root: string,
  registry: Registry,
  dependencies: Record<string, string>,
): InstallationSnippets {
  const globalStyles = readFileSync(join(root, "src/index.css"), "utf8");
  // Reuse the verified theme blocks without documentation-only styles.
  const themeStyles =
    globalStyles.match(/@theme inline \{[\s\S]*?@layer base \{[\s\S]*?\n\}/)?.[0] ?? "";

  if (!themeStyles) {
    throw new Error("Missing nova theme tokens in src/index.css");
  }

  const snippets: Record<InstallationSnippetKey, [HighlightLanguage, string]> = {
    create: [
      "bash",
      `bun create vite my-app --template preact-ts
cd my-app
bun install`,
    ],
    cleanFiles: [
      "bash",
      `rm src/app.css
rm -r src/assets`,
    ],
    cleanCss: [
      "css",
      `/* src/index.css — replace the whole file */
@import "tailwindcss";`,
    ],
    cleanApp: [
      "tsx",
      `// src/app.tsx — replace the whole file
export function App() {
  return <main className="p-8">Hello</main>;
}`,
    ],
    init: ["bash", `${cliCommand} init`],
    geistInstall: ["bash", "bun add --exact @fontsource-variable/geist"],
    geistCss: [
      "css",
      `/* src/index.css */
@import "tailwindcss";
@import "@fontsource-variable/geist";
@import "./shadcn-preact.css";`,
    ],
    add: ["bash", `${cliCommand} add button dialog`],
    usage: [
      "tsx",
      `// src/app.tsx
import { Button } from "./components/ui/button";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogHeader,
  DialogTitle,
  DialogTrigger,
} from "./components/ui/dialog";

export function App() {
  return (
    <main className="flex gap-3 p-8">
      <Button>Continue</Button>

      <Dialog>
        <DialogTrigger render={<Button variant="outline" />}>Open</DialogTrigger>
        <DialogContent>
          <DialogHeader>
            <DialogTitle>Hello</DialogTitle>
            <DialogDescription>Your project is configured.</DialogDescription>
          </DialogHeader>
        </DialogContent>
      </Dialog>
    </main>
  );
}`,
    ],
    verify: [
      "bash",
      `bun run dev     # open the printed URL
bun run build   # type-checks and builds for production`,
    ],
    addTheme: ["bash", `${cliCommand} add theme`],
    main: [
      "tsx",
      `// src/main.tsx
import { render } from "preact";

import { App } from "./app";
import { ThemeProvider } from "./components/ui/theme";
import "./index.css";

render(
  <ThemeProvider defaultTheme="system" storageKey="ui-theme">
    <App />
  </ThemeProvider>,
  document.getElementById("app")!,
);`,
    ],
    options: [
      "bash",
      `${cliCommand} init --path src/components/ui --css src/index.css
${cliCommand} add button --cwd ./apps/web
${cliCommand} add button --overwrite
${cliCommand} add chart --no-install
${cliCommand} add --all
${cliCommand} add sidebar --dry-run`,
    ],
    tree: [
      "text",
      `my-app/
├─ shadcn-preact.json                      # paths used by add
├─ vite.config.ts                          # wrapper: Preact, Tailwind, aliases, stylesheet
├─ vite.config.shadcn-preact.original.ts   # your original config: keep editing this one
├─ shadcn-preact.vite.mts                  # managed integration, regenerated by init
├─ tsconfig*.json                          # jsx, paths, "@/*" alias (comments preserved)
└─ src/
   ├─ index.css                            # + @import "./shadcn-preact.css"
   ├─ shadcn-preact.css                    # animations, @source, dark variant, nova theme
   ├─ shadcn-tailwind.css                  # vendored upstream utilities
   └─ components/ui/
      ├─ lib/utils.ts                      # cn()
      └─ LICENSE.md`,
    ],
    runtimeInstall: [
      "bash",
      `bun add --exact ${exact(registry.setupDependencies)} ${exact(dependencies, sharedPackages)}`,
    ],
    developmentInstall: ["bash", `bun add --dev --exact ${exact(registry.setupDevDependencies)}`],
    manualVite: [
      "tsx",
      `// vite.config.ts
import preact from "@preact/preset-vite";
import tailwindcss from "@tailwindcss/vite";
import { defineConfig } from "vite";

export default defineConfig({
  plugins: [preact(), tailwindcss()],
});`,
    ],
    manualTypescript: [
      "json",
      `{
  "compilerOptions": {
    "jsx": "react-jsx",
    "jsxImportSource": "preact",
    "paths": {
      "react": ["./node_modules/preact/compat/"],
      "react-dom": ["./node_modules/preact/compat/"],
      "react/jsx-runtime": ["./node_modules/preact/jsx-runtime/"],
      "react/jsx-dev-runtime": ["./node_modules/preact/jsx-runtime/"]
    }
  }
}`,
    ],
    copyCatalog: ["bash", copyComponentsCommand],
    manualCss: [
      "css",
      `/* src/index.css */
@import "tailwindcss";
@import "tw-animate-css";
@import "@fontsource-variable/geist";
@import "./styles/shadcn-tailwind.css";

@custom-variant dark (&:is(.dark *));`,
    ],
    themeCss: ["css", themeStyles],
  };

  return Object.fromEntries(
    Object.entries(snippets).map(([key, [language, code]]) => [key, highlightCode(code, language)]),
  ) as InstallationSnippets;
}
